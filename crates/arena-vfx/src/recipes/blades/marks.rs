//! The hand-drawn stroke marks (the engine's `arcane/shuriken` arm and `impacts/drops` teardrop, drawn from the
//! "Free pack, Part 1" sheets): `arcane/twin-shuriken` (two arms), `impacts/star-converge` (four drops) and
//! `impacts/twin-converge` (two drops). Each is one tone ramp: the school's palette, or the ember colourway.

use crate::kit::{Layer, Opts, Painter, Rgba, Show};

use super::tone::{EMBER, Ink, Knot, curve, pose};

/// Seconds a moment of the sheet lasts, and the moments from the first glint to the last fleck.
const MOMENT: f64 = 0.06;
const MOMENTS: f64 = 14.0;
/// How long each mark plays.
pub const SECS: f64 = MOMENTS * MOMENT;

/// Which mark, how many copies round the origin, and the first one's quarter turns.
#[derive(Clone, Copy)]
enum Mark {
    Arm,
    Drop,
}

struct Marks {
    ramp: Vec<Rgba>,
    mark: Mark,
    fold: u32,
    quarters: u32,
}

fn marks(o: &Opts, mark: Mark, fold: u32, quarters: u32) -> Box<dyn Show> {
    Box::new(Marks {
        ramp: o.palette_or(&EMBER),
        mark,
        fold,
        quarters,
    })
}

pub fn twin_shuriken(o: &Opts) -> Box<dyn Show> {
    marks(o, Mark::Arm, 2, 1)
}

pub fn star_converge(o: &Opts) -> Box<dyn Show> {
    marks(o, Mark::Drop, 4, 0)
}

pub fn twin_converge(o: &Opts) -> Box<dyn Show> {
    marks(o, Mark::Drop, 2, 1)
}

impl Show for Marks {
    fn draw(&self, p: &mut Painter, t: f64, layer: Layer) {
        let s = t / MOMENT;
        if layer == Layer::Back || s >= MOMENTS {
            return;
        }
        match self.mark {
            Mark::Arm => arms(p, &self.ramp, s, self.fold, self.quarters),
            Mark::Drop => drops(p, &self.ramp, s, self.fold, self.quarters),
        }
    }
}

/// A knot turned `quarters` quarter turns clockwise.
fn quarter(k: Knot, quarters: u32) -> Knot {
    match quarters % 4 {
        1 => (-k.1, k.0, k.2, k.3),
        2 => (-k.0, -k.1, k.2, k.3),
        3 => (k.1, -k.0, k.2, k.3),
        _ => k,
    }
}

/// The shuriken's arms at moment `s`, `fold` of them round the origin.
fn arms(p: &mut Painter, ramp: &[Rgba], s: f64, fold: u32, quarters: u32) {
    let arm = pose(&ARM, s).map(|k| quarter(k, quarters));
    let spike = pose(&SPIKE, s).map(|k| quarter(k, quarters));
    let mut ink = Ink::new(fold).grain(0.3, 0.55, 15.0);
    ink.path(&arm);
    ink.path(&spike);
    // the shuriken flares (light on its own pixels only)
    let flare = curve(&[(2.5, 0.0), (4.0, 1.0), (7.0, 0.5), (8.5, 0.0)], s);
    ink.paint(p, ramp, 32.0, 0.08 * (1.0 + 2.0 * flare));
}

/// The teardrops at moment `s`, `fold` of them round the origin.
fn drops(p: &mut Painter, ramp: &[Rgba], s: f64, fold: u32, quarters: u32) {
    let drop = pose(&DROP, s).map(|k| quarter(k, quarters));
    let mut ink = Ink::new(fold).grain(0.15, 0.7, 24.0);
    ink.path(&drop);
    // the star flares where they meet
    let flare = curve(&[(7.0, 0.0), (9.0, 1.0), (10.5, 0.0)], s);
    ink.paint(p, ramp, 32.0, 0.08 * (1.0 + 2.0 * flare));
}

