//! The tone-painted seals, drawn by hand in the engine from the "Free pack" sheets: comma seal (four commas close a
//! ring, curl into a square seal, burst into forked blades), shuriken seal (four comets swell into a spiked shuriken
//! square that breaks into hooked blobs), comet rings (broken arcs turning round a core, comets racing round) and
//! vortex ring (a spark winds into a vortex, flashes into a ring, breaks into shards). Each is a one-shot of moments
//! 0.06 s long at 50 fps, 96 px square round its origin, all over the fighters.

use super::tone::{self, Ink, Knot, curve, pose};
use crate::vfx::kit::{Layer, Opts, Painter, Rgba, Show, libm};

/// Seconds a moment of the sheet lasts.
pub const MOMENT: f64 = 0.06;

/// Degrees to radians.
const DEG: f64 = core::f64::consts::PI / 180.0;

#[derive(Clone, Copy)]
enum Kind {
    Comma,
    Shuriken,
    Comet,
    Vortex,
}

struct Seal {
    kind: Kind,
    ramp: Vec<Rgba>,
}

fn seal(o: &Opts, kind: Kind) -> Box<dyn Show> {
    Box::new(Seal {
        kind,
        ramp: tone::ramp(o),
    })
}

pub fn comma_seal(o: &Opts) -> Box<dyn Show> {
    seal(o, Kind::Comma)
}

pub fn shuriken_seal(o: &Opts) -> Box<dyn Show> {
    seal(o, Kind::Shuriken)
}

pub fn comet_rings(o: &Opts) -> Box<dyn Show> {
    seal(o, Kind::Comet)
}

pub fn vortex_ring(o: &Opts) -> Box<dyn Show> {
    seal(o, Kind::Vortex)
}

impl Show for Seal {
    fn draw(&self, p: &mut Painter, t: f64, layer: Layer) {
        let s = t / MOMENT;
        if layer == Layer::Back {
            return;
        }
        let r = &self.ramp;
        match self.kind {
            Kind::Comma if s < 14.0 => comma(p, r, s),
            Kind::Shuriken if s < 14.0 => shuriken(p, r, s),
            Kind::Comet if s < 14.0 => comet(p, r, s),
            Kind::Vortex if s < 13.0 => vortex(p, r, s),
            _ => {}
        }
    }
}

