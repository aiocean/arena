const C_HOOP: [(f64, f64); 5] = [(0.0, -1.0), (1.0, 2.0), (5.0, 3.0), (7.0, 2.0), (8.0, -1.0)];
const OUTER_R: [(f64, f64); 4] = [(0.0, 27.0), (2.0, 26.5), (8.0, 25.5), (12.0, 27.0)];
