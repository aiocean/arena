/// Every effect id, as a duel's config takes them.
pub fn all() -> Vec<String> {
    EFFECTS.iter().map(|(id, _)| (*id).to_string()).collect()
}

/// Whether effect `fx` loops.
pub fn loops(fx: &str) -> bool {
    EFFECTS.iter().any(|&(id, looping)| id == fx && looping)
}
